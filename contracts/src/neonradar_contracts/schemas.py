"""Generated contract files: the JSON Schemas in contracts/schemas/ (PHASE-1.md 5.0, 5.5).

`neonradar contracts export` writes them and `neonradar contracts check` fails on any drift
between the models and the committed files. Each file is the model's
`model_json_schema()` with sorted keys and two-space indentation, so the output is stable.
M1.7d adds the OpenAPI snapshot (contracts/openapi/v1.json) through the command line.
"""

import json
from collections.abc import Mapping
from pathlib import Path
from tempfile import TemporaryDirectory

from pydantic import BaseModel

from neonradar_contracts.alert import Alert

# The workspace installs members editable, so this is the contracts/ folder of the repository.
CONTRACTS_DIR = Path(__file__).resolve().parents[2]


def render_json(document: object) -> str:
    """Stable JSON text: sorted keys, two-space indentation, UTF-8, final newline."""
    return json.dumps(document, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def documents() -> dict[str, str]:
    """Every generated file of the contracts package, by path relative to contracts/."""
    # Imported here: the C1 models load FollowTheMoney, which `alert` does not need.
    from neonradar_contracts.records import Manifest, NrExtension

    models: dict[str, type[BaseModel]] = {
        "schemas/alert.v1.json": Alert,
        "schemas/record-manifest.v1.json": Manifest,
        "schemas/record-nr.v1.json": NrExtension,
    }
    return {path: render_json(model.model_json_schema()) for path, model in models.items()}


def export(root: Path = CONTRACTS_DIR, docs: Mapping[str, str] | None = None) -> list[Path]:
    """Write the generated files under `root`; return their paths."""
    written = []
    for relative, text in sorted((documents() if docs is None else docs).items()):
        path = root / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        written.append(path)
    return written


def check(root: Path = CONTRACTS_DIR, docs: Mapping[str, str] | None = None) -> list[str]:
    """Export to a temporary folder and compare with `root`; one line per difference.

    A generated folder (for example `schemas/`) may hold only generated files, so a stale
    schema left behind by a rename counts as a difference too.
    """
    docs = documents() if docs is None else docs
    problems = []
    with TemporaryDirectory() as tmp:
        export(Path(tmp), docs)
        for relative in sorted(docs):
            committed = root / relative
            if not committed.is_file():
                problems.append(f"{relative}: missing; run `make contracts`")
            elif committed.read_bytes() != (Path(tmp) / relative).read_bytes():
                problems.append(f"{relative}: differs from the models; run `make contracts`")
    for folder in sorted({Path(relative).parts[0] for relative in docs}):
        for path in sorted((root / folder).rglob("*")):
            relative = path.relative_to(root).as_posix()
            if path.is_file() and not path.name.startswith(".") and relative not in docs:
                problems.append(f"{relative}: not generated by `neonradar contracts export`")
    return problems
