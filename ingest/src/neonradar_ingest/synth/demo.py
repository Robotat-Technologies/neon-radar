"""The demo-mini fixture: `neonradar synth demo-mini` (PHASE-1.md M1.8e deliverable 2)."""

from pathlib import Path

from neonradar_ingest.synth.activity import demo_activity
from neonradar_ingest.synth.emit import write_load
from neonradar_ingest.synth.registry import build_registry

DEMO_SEED = 20261023
AS_OF = "20261023"  # the file-name date is fixed, so output never depends on the clock
STEM = f"nr_synthetic-{AS_OF}-demo-mini"
# Name draws skipped because the name matched the Companies House register (OD-12): record id
# to the first draw to use. Checked on the date given; see the M1.8e pull request.
REDRAW: dict[str, int] = {}
NOTES = [
    "Synthetic demo-mini fixture (PHASE-1.md M1.8e). Every company, person, address, account"
    " and payment was generated by NeonRadar; none of them exists.",
    "Ground-truth labels are in labels/transactions.csv and labels/scenarios.csv, never in the"
    " records. Payments missing from transactions.csv are background activity.",
    "Regenerate with: neonradar synth demo-mini --seed 20261023 --out data/fixtures/demo-mini/"
    " (then check every new name against the Companies House search, OD-12).",
]


def write_demo_mini(out: Path, seed: int = DEMO_SEED, created_at: str | None = None) -> Path:
    """Generate demo-mini into `out`; return the path of the record file."""
    registry = build_registry(seed, REDRAW if seed == DEMO_SEED else None)
    scenarios = demo_activity(registry, seed)
    return write_load(
        out, STEM, registry.records, scenarios, seed=seed, notes=NOTES, created_at=created_at
    )
