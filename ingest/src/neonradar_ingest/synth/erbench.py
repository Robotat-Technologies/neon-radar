@cache
def arabic_given() -> dict[str, tuple[tuple[str, tuple[str, ...]], ...]]:
    """Faker ar_SA given names that `variants.ARABIC_GIVEN` spells: (Faker form, Latin)."""
    faker = {"male": ar_SA.Provider.first_names_male, "female": ar_SA.Provider.first_names_female}
    out = {}
    for gender, table in variants.ARABIC_GIVEN.items():
        found = {strip_marks(name): name for name in sorted(faker[gender])}
        out[gender] = tuple((found[key], latin) for key, latin in table.items() if key in found)
    return out


@cache
def russian_given() -> dict[str, tuple[tuple[str, tuple[str, ...], tuple[str, ...]], ...]]:
    faker = {"male": ru_RU.Provider.first_names_male, "female": ru_RU.Provider.first_names_female}
    return {
        gender: tuple((name, *forms) for name, forms in table.items() if name in faker[gender])
        for gender, table in variants.RUSSIAN_GIVEN.items()
    }


def romanise(cyrillic: str, system: str) -> str:
    """A Cyrillic name in one of the `variants.ROMANISATION` systems, capitalised."""
    table, out, previous = variants.ROMANISATION[system], [], ""
    for char in cyrillic.lower():
        bgn_ye = system == "bgn" and char == "е" and (not previous or previous in variants.YE_AFTER)
        out.append("ye" if bgn_ye else table.get(char, char))
        previous = char
    text = "".join(out)
    return text[:1].upper() + text[1:]


def cyrillic_part(name: str) -> Part:
    """A Cyrillic surname or patronymic with its Latin spellings (BGN/PCGN canonical)."""
    base = romanise(name, "bgn")
    forms = [base]
    for ending, others in variants.ENDINGS:
        if base.endswith(ending):
            forms += [base[: -len(ending)] + other for other in others]
            break
    forms += [romanise(name, "icao"), romanise(name, "french")]
    return Part(_dedupe(forms), name)


def arabic_surname(arabic: str, latin: tuple[str, ...], article: bool) -> Part:
    if not article:
        return Part(latin, arabic)
    joined = [f"Al{root.lower()}" for root in latin[:1]]
    spaced = [f"{form}{root}" for form in variants.ARTICLE_FORMS[:3] for root in latin]
    return Part(_dedupe([spaced[0], *spaced[1:], *joined]), variants.ARABIC_ARTICLE + arabic)


@cache
def faker_surnames() -> tuple[frozenset[str], frozenset[str]]:
    """Faker's en_GB, ar_SA and ru_RU surnames (folded), and the Latin forms of the ru_RU ones
    and of the curated Arabic surnames: an invented surname must be none of them."""
    native = {fold(name) for name in en_GB.Provider.last_names}
    for name in ar_SA.Provider.last_names:
        native |= {fold(name), fold(name.removeprefix("آل ").removeprefix("ال"))}
    russian = {*ru_RU.Provider.last_names_male, *ru_RU.Provider.last_names_female}
    native |= {fold(name) for name in russian}
    latin = {fold(form) for name in russian for form in cyrillic_part(name).latin}
    latin |= {fold(form) for _, forms in variants.ARABIC_SURNAMES for form in forms}
    return frozenset(native), frozenset(latin)


def invented_surname(rng: np.random.Generator, origin: str) -> Part:
    """Two or three invented syllables in the person's script (deliverable 2); three more often,
    because two syllables form real surnames more easily."""
    count = 3 if chance(rng, 0.7) else 2
    picked = [variants.SYLLABLES[int(i)] for i in rng.choice(len(variants.SYLLABLES), count)]
    spellings = [""]
    for forms, _, _ in picked:
        spellings = [s + form for s in spellings for form in forms][:4]
    latin = _dedupe([s.capitalize() for s in spellings])
    if origin == "ar":
        return Part(latin, "".join(arabic for _, arabic, _ in picked))
    if origin == "ru":
        return Part(latin, "".join(cyr for _, _, cyr in picked).capitalize())
    return Part(latin)


@cache
def _not_invented() -> frozenset[str]:
    return frozenset(fold(name) for name in variants.NOT_INVENTED)


def invented_ok(part: Part) -> bool:
    native, latin = faker_surnames()
    forms = [fold(form) for form in part.latin]
    if any(form in native or form in latin or form in _not_invented() for form in forms):
        return False
    return part.native is None or fold(part.native) not in native


