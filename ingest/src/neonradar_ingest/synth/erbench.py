@dataclass
class Bench:
    """A generated benchmark: records, truth rows and the variation counts of `RATES`."""

    people: list[Person]
    orgs: list[Org]
    records: list[Rec] = field(default_factory=list)
    truth: list[tuple[str, str, str, str, str]] = field(default_factory=list)
    stats: Counter[str] = field(default_factory=Counter)
    authority_ids: Counter[str] = field(default_factory=Counter)
    partner: dict[str, str] = field(default_factory=dict)  # entity id -> its twin's

    def add(self, rec: Rec, entity_id: str, cls: str, style: str, twin: str) -> None:
        self.records.append(rec)
        self.truth.append((rec.id, entity_id, cls, style, twin))

    def count(self, key: str, hit: bool) -> bool:
        self.stats[f"{key}.n"] += 1
        self.stats[key] += hit
        return hit

    def sanction(self, entity: str, authority: str, unsc: str | None) -> None:
        self.authority_ids[authority] += 1
        native_id = f"SY{authority[-1]}-{UNISSUED + self.authority_ids[authority]}"
        props = {"entity": [entity], "authority": [authority], "authorityId": [native_id]}
        if unsc:
            props["unscId"] = [unsc]
        self.records.append(
            Rec(_edge_id("Sanction", entity, authority), "Sanction", "list", props, _v11())
        )


def _v11(**extra: Any) -> dict[str, Any]:
    return {"v": "1.1", **extra}


def record_id(cls: str, number: int, k: int) -> str:
    return make_id(SYNTHETIC_PREFIX, "erb", f"{cls}-{number:05d}-{k:02d}")


def typo(rng: np.random.Generator, text: str) -> str:
    """One substitution, deletion or transposition inside a letter run of four or more."""
    tokens = text.split(" ")
    options = [i for i, t in enumerate(tokens) if sum(c.isalpha() for c in t) >= 4]
    if not options:
        return text
    index = pick(rng, options)
    token = tokens[index]
    spots = [i for i in range(1, len(token) - 1) if token[i].isalpha() and token[i + 1].isalpha()]
    if not spots:
        return text
    at, operation = pick(rng, spots), int(rng.integers(3))
    if operation == 0:
        pool = "aeiou" if token[at].lower() in "aeiou" else "bdfghklmnrstvz"
        new = pick(rng, [c for c in pool if c != token[at].lower()])
        token = token[:at] + (new.upper() if token[at].isupper() else new) + token[at + 1 :]
    elif operation == 1:
        token = token[:at] + token[at + 1 :]
    elif token[at] != token[at + 1]:
        token = token[:at] + token[at + 1] + token[at] + token[at + 2 :]
    else:
        token = token[:at] + token[at + 2 :]
    tokens[index] = token
    return " ".join(tokens)


@dataclass(slots=True)
class Shown:
    """How one record writes a person's name."""

    given: str
    middle: str | None
    surname: str

    def full(self, swap: bool = False) -> str:
        parts = (self.surname, self.given, self.middle) if swap else (
            self.given, self.middle, self.surname)  # fmt: skip
        return " ".join(part for part in parts if part)


def _show(bench: Bench, rng: np.random.Generator, person: Person) -> Shown:
    given, surname = person.given.latin[0], person.surname.latin[0]
    middle = person.middle.latin[0] if person.middle else None
    if person.origin != "en" and bench.count("variant", chance(rng, RATES["variant"])):
        parts = [p for p in ("given", "middle", "surname") if _alternatives(person, p)]
        chosen = [p for p in parts if chance(rng, 0.5)]
        if parts and not chosen:
            chosen = [pick(rng, parts)]
        for name in chosen:
            spelling = pick(rng, _alternatives(person, name))
            given, middle, surname = (spelling if name == "given" else given,
                                      spelling if name == "middle" else middle,
                                      spelling if name == "surname" else surname)  # fmt: skip
    if middle is not None:
        draw = rng.random()
        if bench.count("middle_initial", draw < RATES["middle_initial"]):
            middle = middle[0]
        limit = RATES["middle_initial"] + RATES["middle_dropped"]
        if bench.count("middle_dropped", RATES["middle_initial"] <= draw < limit):
            middle = None
    before = (given, surname)
    if chance(rng, RATES["typo"]):
        if chance(rng, 0.5):
            given = typo(rng, given)
        else:
            surname = typo(rng, surname)
    bench.count("typo", (given, surname) != before)  # only typos that changed a name count
    return Shown(given, middle, surname)


def _alternatives(person: Person, part: str) -> tuple[str, ...]:
    value: Part | None = getattr(person, part)
    return value.latin[1:] if value else ()


def _nationality(bench: Bench, rng: np.random.Generator, person: Person) -> dict[str, list[str]]:
    missing = bench.count("nationality_missing", chance(rng, RATES["nationality_missing"]))
    return {} if missing else {"nationality": list(person.nationalities)}


def _band(rng: np.random.Generator) -> tuple[dict[str, list[str]], dict[str, Any]]:
    band = pick(rng, sorted(BANDS))
    low, high, low_open, high_open = BANDS[band]
    nature = f"ownership-of-shares-{band.replace('-', '-to-')}-percent"
    nr: dict[str, Any] = {"natures_of_control": [nature], "share_pct_min": low,
                          "share_pct_max": high}  # fmt: skip
    if low_open:
        nr["share_pct_min_exclusive"] = True
    if high_open:
        nr["share_pct_max_exclusive"] = True
    return {"percentage": [band], "role": [nature]}, nr


def _start(rng: np.random.Generator, after: date) -> str:
    """An appointment or holding start after `after`, never after `LATEST` (no clock)."""
    return min(after + timedelta(days=between(rng, 30, 3000)), LATEST).isoformat()


def person_records(bench: Bench, seed: int, person: Person, orgs: list[Org]) -> None:
    style_rng = _rng(seed, RECORD, 1, person.number, 0)
    styles = [pick(style_rng, ("officer", "psc")) for _ in range(person.n_registry)]
    styles += ["list"] * len(person.authorities) + ["leak"] * person.leaked
    twin = f"{SYNTHETIC_PREFIX}-erb-p-{person.twin_of:05d}" if person.twin_of else ""
    twin = twin or bench.partner.get(person.entity_id, "")
    adult = date(person.birth.year + 18, person.birth.month, 1)
    authorities = iter(person.authorities)
    for k, style in enumerate(styles, start=1):
        rng = _rng(seed, RECORD, 1, person.number, k)
        rid, shown = record_id("p", person.number, k), _show(bench, rng, person)
        props: dict[str, list[str]] = {}
        nr = _v11()
        if style in ("officer", "psc"):
            moved = bench.count("moved", chance(rng, RATES["moved"]))
            home = address(rng, postcode(rng)) if moved else person.home
            org = orgs[pick(rng, person.portfolio) - 1]
            start = _start(rng, max(org.incorporated, adult))
        if style == "officer":
            forenames = " ".join(part for part in (shown.given, shown.middle) if part)
            props = {"name": [f"{shown.surname.upper()}, {forenames}"], "firstName": [forenames],
                     "lastName": [shown.surname.upper()],
                     "birthDate": [person.birth.strftime("%Y-%m")]}  # fmt: skip
            props |= _nationality(bench, rng, person) | {"address": [home]}
            draw = rng.random()
            primary = bench.count("pn_primary", draw < RATES["pn_primary"])
            limit = RATES["pn_primary"] + RATES["pn_secondary"]
            secondary = bench.count("pn_secondary", RATES["pn_primary"] <= draw < limit)
            if primary or secondary:
                prefix = person.person_numbers[0 if primary else 1]
                nr["ch_person_number"] = f"{prefix}{between(rng, 1, 9):04d}"
            role = "secretary" if chance(rng, 0.15) else "director"
            target = record_id("o", org.number, 1)
            bench.records.append(Rec(
                _edge_id("Directorship", rid, target, role, start), "Directorship", "registry",
                {"director": [rid], "organization": [target], "role": [role],
                 "startDate": [start]}, _v11()))  # fmt: skip
            schema = "Person"
        elif style == "psc":
            title = pick(rng, TITLES[person.gender])
            props = {"name": [f"{title} {shown.full()}"], "title": [title],
                     "firstName": [shown.given], "lastName": [shown.surname],
                     "birthDate": [person.birth.strftime("%Y-%m")]}  # fmt: skip
            if shown.middle:
                props["middleName"] = [shown.middle]
            props |= _nationality(bench, rng, person) | {"address": [home]}
            band, band_nr = _band(rng)
            target = record_id("o", org.number, 1)
            bench.records.append(Rec(
                _edge_id("Ownership", rid, target, "shares"), "Ownership", "registry",
                {"owner": [rid], "asset": [target], "startDate": [start], **band},
                _v11(**band_nr)))  # fmt: skip
            schema = "Person"
        elif style == "list":
            swap = bench.count("swap", chance(rng, RATES["swap"]))
            props = {"name": [shown.full(swap)], "alias": _person_aliases(rng, person, shown)}
            props |= {"birthDate": _list_birth(bench, rng, person.birth)}
            props |= _nationality(bench, rng, person)
            props |= {"gender": [person.gender], "topics": ["sanction"]}
            bench.sanction(rid, next(authorities), person.unsc)
            schema = "Person"
        else:
            props = {"name": [shown.full().upper()]}
            if chance(rng, 0.5):
                props["country"] = [person.nationalities[0]]
            schema = "LegalEntity"
        bench.add(
            Rec(rid, schema, KIND[style], {p: v for p, v in props.items() if v}, nr),
            person.entity_id,
            "person",
            style,
            twin,
        )


def _person_aliases(rng: np.random.Generator, person: Person, shown: Shown) -> list[str]:
    aliases: list[str] = []
    if person.given.native and person.surname.native:
        middle = person.middle.native if person.middle else None
        parts = (person.given.native, middle, person.surname.native)
        aliases.append(" ".join(part for part in parts if part))
    other = [f"{g} {s}" for g in person.given.latin for s in person.surname.latin]
    other = [name for name in other if name != f"{shown.given} {shown.surname}"]
    if other:
        aliases.append(pick(rng, other))
    return aliases


def _list_birth(bench: Bench, rng: np.random.Generator, born: date) -> list[str]:
    draw, limit = rng.random(), RATES["birth_full"] + RATES["birth_year"]
    full = bench.count("birth_full", draw < RATES["birth_full"])
    if bench.count("birth_year", RATES["birth_full"] <= draw < limit):
        return [str(born.year)]
    if full:
        return [born.isoformat()]
    shift = 1 if chance(rng, 0.5) else -1
    leap_day = (born.month, born.day) == (2, 29)
    other = date(born.year + shift, born.month, 28 if leap_day else born.day)
    return sorted([born.isoformat(), other.isoformat()])


def _org_name(bench: Bench, rng: np.random.Generator, org: Org) -> str:
    core, form = list(org.core), org.form
    if bench.count("org_form", chance(rng, RATES["org_form"])):
        form = pick(rng, FORM_SPELLINGS[org.form][1:])
    if "&" in core and bench.count("org_amp", chance(rng, RATES["org_amp"])):
        core[core.index("&")] = "and"
    separator, end = " ", ""
    if bench.count("org_punct", chance(rng, RATES["org_punct"])):
        kind = int(rng.integers(3))
        if kind == 1 and core[1] not in ("&", "and"):  # "Alder-Brae Trading Ltd"
            core[0:2] = [f"{core[0]}-{core[1]}"]
        elif kind != 0 and not form.endswith("."):  # "Alder Brae Trading Ltd."
            end = "."
        else:  # "Alder Brae Trading, Ltd"
            separator = ", "
    if chance(rng, RATES["org_typo"]):
        index = between(rng, 0, len(core) - 1)
        word = core[index]
        core[index] = typo(rng, word)
        bench.count("org_typo", core[index] != word)
    else:
        bench.count("org_typo", False)
    name = f"{' '.join(core)}{separator}{form}{end}"
    if bench.count("org_the", chance(rng, RATES["org_the"])):
        name = f"The {name}"
    return name


def org_records(bench: Bench, seed: int, org: Org, orgs: list[Org]) -> None:
    styles = ["registry"] + ["registry"] * org.has_lei + list(org.corporate)
    styles += ["list"] * bool(org.listed) + ["leak"] * org.leaked
    twin = f"{SYNTHETIC_PREFIX}-erb-o-{org.twin_of:05d}" if org.twin_of else ""
    twin = twin or bench.partner.get(org.entity_id, "")
    uk = {"registrationNumber": [org.company_number], "jurisdiction": ["gb"]}
    for k, style in enumerate(styles, start=1):
        rng = _rng(seed, RECORD, 2, org.number, k)
        rid, name = record_id("o", org.number, k), _org_name(bench, rng, org)
        schema, props = "Company", {"name": [name]}
        if k == 1:  # Free Company Data: the register's upper-case name
            props = {"name": [name.upper()], **uk,
                     "incorporationDate": [org.incorporated.isoformat()],
                     "address": [org.address]}  # fmt: skip
        elif style == "registry":  # GLEIF: legal name, company number and LEI
            props |= {**uk, "leiCode": [org.lei] if org.lei else [], "address": [org.address]}
        elif style in ("officer", "psc"):
            other = orgs[pick(rng, [o.number for o in orgs if o.number != org.number]) - 1]
            target, start = record_id("o", other.number, 1), _start(rng, other.incorporated)
            if style == "officer":
                props = {"name": [name.upper()], **uk}
                role = "corporate-director" if chance(rng, 0.8) else "corporate-secretary"
                bench.records.append(Rec(
                    _edge_id("Directorship", rid, target, role, start), "Directorship",
                    "registry", {"director": [rid], "organization": [target], "role": [role],
                                 "startDate": [start]}, _v11()))  # fmt: skip
            else:
                with_number = bench.count("corp_psc_number", chance(rng, RATES["corp_psc_number"]))
                props |= uk if with_number else {"jurisdiction": ["gb"]}
                schema = "Company" if with_number else "LegalEntity"
                band, band_nr = _band(rng)
                bench.records.append(Rec(
                    _edge_id("Ownership", rid, target, "shares"), "Ownership", "registry",
                    {"owner": [rid], "asset": [target], "startDate": [start], **band},
                    _v11(**band_nr)))  # fmt: skip
        elif style == "list":
            schema = "Organization"
            alias = _org_name(bench, rng, org)
            props |= {"alias": [alias] if alias != name else [], "topics": ["sanction"]}
            if bench.count("org_list_number", chance(rng, RATES["org_list_number"])):
                props |= uk
            bench.sanction(rid, org.listed or AUTHORITIES[0], org.unsc)
        else:  # leak
            props = {"name": [name.upper() if chance(rng, 0.5) else name], "jurisdiction": ["gb"]}
        kind = KIND[style]
        bench.add(
            Rec(rid, schema, kind, {p: v for p, v in props.items() if v}, _v11()),
            org.entity_id,
            "org",
            style,
            twin,
        )


def build(size: str, seed: int = ER_BENCH_SEED) -> Bench:
    """Generate the benchmark in memory."""
    n_people, n_orgs = SIZES[size]
    orgs = plan_orgs(seed, n_orgs)
    bench = Bench(plan_people(seed, n_people, n_orgs), orgs)
    entities: list[Person | Org] = [*bench.people, *orgs]
    for entity in entities:
        if entity.twin_of is not None:
            cls = "p" if isinstance(entity, Person) else "o"
            bench.partner[f"{SYNTHETIC_PREFIX}-erb-{cls}-{entity.twin_of:05d}"] = entity.entity_id
    for org in orgs:
        org_records(bench, seed, org, orgs)
    for person in bench.people:
        person_records(bench, seed, person, orgs)
    return bench


def write_er_bench(
    out: Path, size: str = "small", seed: int = ER_BENCH_SEED, created_at: str | None = None
) -> Path:
    """Write `<stem>.ftm.jsonl`, its manifest and `labels/er_truth.csv`; return the record file."""
    bench = build(size, seed)
    out.mkdir(parents=True, exist_ok=True)
    path = out / f"{STEM}.ftm.jsonl"
    write_text(path, "".join(rec.to_json() + "\n" for rec in ordered(bench.records)))
    (out / "labels").mkdir(exist_ok=True)
    write_csv(out / "labels" / "er_truth.csv", TRUTH_COLUMNS, sorted(bench.truth))
    producer = Producer(name=GENERATOR, version=GENERATOR_VERSION, git_sha=None)
    size_note = f"Size {size}: {len(bench.people)} people, {len(bench.orgs)} organisations."
    write_manifest(
        path, dataset=SYNTHETIC_DATASET, producer=producer, seed=seed, notes=[*NOTES, size_note],
        created_at=created_at,
    )  # fmt: skip
    amend_manifest(path, seed)
    return path
