def _rng(seed: int, *key: int) -> np.random.Generator:
    """An independent stream of the benchmark, keyed by integers (synth.rng rules apply)."""
    spawn = (COMPONENTS["erbench"], *key)
    return np.random.default_rng(np.random.SeedSequence(seed, spawn_key=spawn))


def _quota[T](rng: np.random.Generator, n: int, shares: Sequence[tuple[T, float]]) -> list[T]:
    """Exactly `round(n * share)` of each value (the last takes the rest), in seeded order."""
    counts = [round(n * share) for _, share in shares]
    counts[-1] = n - sum(counts[:-1])
    plan = [value for (value, _), count in zip(shares, counts, strict=True) for _ in range(count)]
    return [plan[int(i)] for i in rng.permutation(n)]


def _subset(rng: np.random.Generator, n: int, share: float) -> list[bool]:
    return _quota(rng, n, ((True, share), (False, 1 - share)))


def _edge_id(schema: str, *parts: str) -> str:
    """PHASE-1.md 4.4: `syn-<schema>-<first 20 hex of sha1 of the parts joined by |>`."""
    digest = hashlib.sha1("|".join(parts).encode("utf-8"), usedforsecurity=False).hexdigest()
    return make_id(SYNTHETIC_PREFIX, schema.lower(), digest[:20])


def _dedupe(items: Sequence[str]) -> tuple[str, ...]:
    return tuple(dict.fromkeys(item for item in items if item))


def strip_marks(text: str) -> str:
    return unicodedata.normalize("NFC", text).translate(_MARKS)


@dataclass(frozen=True, slots=True)
class Part:
    """One part of a name: Latin spellings (canonical first) and the original script."""

    latin: tuple[str, ...]
    native: str | None = None


