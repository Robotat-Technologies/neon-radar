@dataclass(slots=True)
class Person:
    number: int
    origin: str  # en, ar or ru (Russian or Ukrainian)
    ukrainian: bool
    gender: str
    n_registry: int  # officer and PSC records
    authorities: tuple[str, ...]  # one list record per authority
    leaked: bool
    has_middle: bool
    invented: bool = False
    twin_of: int | None = None
    given: Part = Part(("",))
    middle: Part | None = None
    surname: Part = Part(("",))
    birth: date = date(1970, 1, 1)
    nationalities: tuple[str, ...] = ()
    home: str = ""
    postcode: str = ""
    person_numbers: tuple[str, str] = ("", "")
    portfolio: tuple[int, ...] = ()
    unsc: str | None = None

    @property
    def entity_id(self) -> str:
        return f"{SYNTHETIC_PREFIX}-erb-p-{self.number:05d}"


@dataclass(slots=True)
class Org:
    number: int
    listed: str | None
    leaked: bool
    has_lei: bool
    twin_of: int | None = None
    core: tuple[str, ...] = ()
    form: str = "Ltd"
    company_number: str = ""
    lei: str | None = None
    incorporated: date = date(2000, 1, 1)
    address: str = ""
    corporate: tuple[str, ...] = ()
    unsc: str | None = None

    @property
    def entity_id(self) -> str:
        return f"{SYNTHETIC_PREFIX}-erb-o-{self.number:05d}"

    @property
    def name(self) -> str:
        return f"{' '.join(self.core)} {self.form}"


def lei_check_digits(body: str) -> str:
    """ISO 17442 (ISO 7064 MOD 97-10) check digits of an 18-character LEI body."""
    number = int("".join(str(LEI_CHARS.index(char)) for char in body) + "00")
    return f"{98 - number % 97:02d}"


def postcode(rng: np.random.Generator, district: int | None = None) -> str:
    """A `QQ` postcode: no real UK postcode area starts with Q."""
    district = district if district is not None else between(rng, 1, 99)
    inward = f"{between(rng, 0, 9)}{pick(rng, INWARD_LETTERS)}{pick(rng, INWARD_LETTERS)}"
    return f"QQ{district} {inward}"


def address(rng: np.random.Generator, code: str) -> str:
    return f"{between(rng, 2, 180)} {street(rng)}, {pick(rng, words.CITIES['gb'])}, {code}"


def _twins(rng: np.random.Generator, n: int, share: float) -> dict[int, int]:
    """Twin number -> original number, for `round(n * share)` distinct pairs."""
    count, order = round(n * share), [int(i) + 1 for i in rng.permutation(n)]
    return dict(zip(order[:count], order[count : 2 * count], strict=True))


def plan_orgs(seed: int, n: int) -> list[Org]:
    rng = _rng(seed, PLAN, 1)
    twins = _twins(rng, n, SHARES["org_twin"])
    lei, listed = _subset(rng, n, SHARES["org_lei"]), _subset(rng, n, SHARES["org_listed"])
    leaked = _subset(rng, n, SHARES["org_leaked"])
    numbers = rng.choice(900_000, n, replace=False) + 100_000
    unsc = rng.choice(4_000, n, replace=False) + UNISSUED  # organisations: 990000 to 993999
    orgs: list[Org] = []
    for i in range(n):
        org_rng = _rng(seed, ORG, i + 1)
        org = Org(i + 1, pick(org_rng, AUTHORITIES) if listed[i] else None, leaked[i], lei[i])
        org.twin_of = twins.get(org.number)
        org.company_number = f"SY{int(numbers[i]):06d}"
        if org.has_lei:
            body = "SYN000" + "".join(pick(org_rng, LEI_CHARS) for _ in range(12))
            org.lei = body + lei_check_digits(body)
        org.incorporated = date(1990, 1, 1) + timedelta(days=between(org_rng, 0, 12783))
        org.address = address(org_rng, postcode(org_rng))
        styles = ("officer", "psc")
        org.corporate = tuple(pick(org_rng, styles) for _ in range(1 + chance(org_rng, 0.5)))
        if org.listed and chance(org_rng, RATES["unsc"]):
            org.unsc = f"ZZe.{int(unsc[i])}"  # the UN writes "e" for entities
        orgs.append(org)
    _name_orgs(seed, orgs)
    return orgs


def _org_core(rng: np.random.Generator) -> tuple[tuple[str, ...], str]:
    first = pick(rng, words.COMPANY_FIRST)
    if chance(rng, RATES["org_amp_name"]):
        other = pick(rng, [w for w in words.COMPANY_FIRST if w != first])
        core: tuple[str, ...] = (first, "&", other, pick(rng, words.COMPANY_ACTIVITY))
    else:
        core = (first, pick(rng, words.COMPANY_SECOND), pick(rng, words.COMPANY_ACTIVITY))
    return core, _form(rng)


def _form(rng: np.random.Generator) -> str:
    draw, total = rng.random(), 0.0
    for form, share in FORMS:
        total += share
        if draw < total:
            return form
    return FORMS[-1][0]


def _name_orgs(seed: int, orgs: list[Org]) -> None:
    taken: set[str] = set()
    for org in (o for o in orgs if o.twin_of is None):
        first = REDRAW.get(org.entity_id, 0)
        for attempt in range(first, first + MAX_TRIES):
            core, form = _org_core(_rng(seed, ORG_NAME, org.number, attempt))
            key = fold(" ".join(core))
            spellings = [f"{' '.join(core)} {s}" for s in FORM_SPELLINGS[form]]
            if key in taken or any(is_denied(name) for name in spellings):
                continue
            taken.add(key)
            org.core, org.form = core, form
            break
        else:
            raise RuntimeError(f"no new organisation name after {MAX_TRIES} tries")
    by_number = {org.number: org for org in orgs}
    for org in orgs:
        if org.twin_of is None:
            continue
        original = by_number[org.twin_of]
        rng = _rng(seed, ORG_NAME, org.number, 0)
        org.core = original.core
        org.form = pick(rng, [form for form, _ in FORMS if form != original.form])


def plan_people(seed: int, n: int, n_orgs: int) -> list[Person]:
    rng = _rng(seed, PLAN, 2)
    origins = _quota(rng, n, ORIGINS)
    counts = _quota(rng, n, RECORD_COUNTS)
    listed, leaked = _subset(rng, n, SHARES["listed"]), _subset(rng, n, SHARES["leaked"])
    middle = _subset(rng, n, SHARES["middle"])
    twins = _twins(rng, n, SHARES["twin"])
    numbers = rng.choice(90_000, 2 * n, replace=False) + 10_000
    unsc = rng.choice(6_000, n, replace=False) + UNISSUED + 4_000  # people: 994000 to 999999
    people: list[Person] = []
    for i in range(n):
        p_rng = _rng(seed, PERSON, i + 1)
        authorities: tuple[str, ...] = ()
        if listed[i]:
            k = between(p_rng, 1, 3)
            authorities = tuple(sorted(str(a) for a in p_rng.choice(AUTHORITIES, k, False)))
        person = Person(
            i + 1, origins[i], chance(p_rng, 0.5), "female" if chance(p_rng, 0.5) else "male",
            counts[i], authorities, leaked[i], middle[i],
        )  # fmt: skip
        person.twin_of = twins.get(person.number)
        person.person_numbers = (f"SYN{int(numbers[2 * i])}", f"SYN{int(numbers[2 * i + 1])}")
        person.portfolio = tuple(
            int(o) + 1 for o in p_rng.choice(n_orgs, between(p_rng, 1, 3), replace=False)
        )
        if authorities and chance(p_rng, RATES["unsc"]):
            person.unsc = f"ZZi.{int(unsc[i])}"
        people.append(person)
    by_number = {p.number: p for p in people}
    for twin in people:
        if twin.twin_of is None:
            continue
        original = by_number[twin.twin_of]
        twin.origin, twin.ukrainian, twin.gender = (
            original.origin,
            original.ukrainian,
            original.gender,
        )
        exposed = bool(twin.authorities or twin.leaked or original.authorities or original.leaked)
        twin.invented = original.invented = exposed
    for person in people:
        person.invented = person.invented or bool(person.authorities or person.leaked)
    _name_people(seed, people)
    _details(seed, people, by_number)
    return people


def _given(rng: np.random.Generator, fakers: dict[str, Faker], person: Person) -> Part:
    if person.origin == "en":
        fake = fakers["en"]
        fake.seed_instance(int(rng.integers(2**32)))
        male = person.gender == "male"
        return Part((fake.first_name_male() if male else fake.first_name_female(),))
    if person.origin == "ar":
        arabic, latin = pick(rng, arabic_given()[person.gender])
        return Part(latin, arabic)
    cyrillic, russian, ukrainian = pick(rng, russian_given()[person.gender])
    latin = (*ukrainian, *russian) if person.ukrainian and ukrainian else (*russian, *ukrainian)
    return Part(_dedupe(latin), cyrillic)


def _middle(rng: np.random.Generator, fakers: dict[str, Faker], person: Person) -> Part:
    if person.origin == "ru":
        names = getattr(ru_RU.Provider, f"middle_names_{person.gender}")
        return cyrillic_part(pick(rng, sorted(names)))
    if person.origin == "ar":  # the father's name
        arabic, latin = pick(rng, arabic_given()["male"])
        return Part(latin, arabic)
    return _given(rng, fakers, person)


def _surname(rng: np.random.Generator, fakers: dict[str, Faker], person: Person) -> Part:
    if person.invented:
        return invented_surname(rng, person.origin)
    if person.origin == "en":
        fake = fakers["en"]
        fake.seed_instance(int(rng.integers(2**32)))
        return Part((fake.last_name(),))
    if person.origin == "ar":
        arabic, latin = pick(rng, variants.ARABIC_SURNAMES)
        return arabic_surname(arabic, latin, chance(rng, 0.4))
    names = getattr(ru_RU.Provider, f"last_names_{person.gender}")
    return cyrillic_part(pick(rng, names))


def _full_names(given: Part, middle: Part | None, surname: Part) -> list[str]:
    """Every form a record can show: given and surname, with the middle name and without."""
    middles = [""] + [f"{m} " for m in (middle.latin if middle else ())]
    names = [f"{g} {m}{s}" for g in given.latin for m in middles for s in surname.latin]
    names += [f"{m}{s}" for m in middles[1:] for s in surname.latin]
    if given.native and surname.native:
        native = f"{middle.native} " if middle and middle.native else ""
        names += [f"{given.native} {surname.native}", f"{given.native} {native}{surname.native}"]
    return names


def _name_people(seed: int, people: list[Person]) -> None:
    fakers = {"en": Faker("en_GB")}
    taken: set[str] = set()
    by_number = {p.number: p for p in people}
    for person in (p for p in people if p.twin_of is None):
        first = REDRAW.get(person.entity_id, 0)
        for attempt in range(first, first + MAX_TRIES):
            rng = _rng(seed, NAME, person.number, attempt)
            given, surname = _given(rng, fakers, person), _surname(rng, fakers, person)
            middle = _middle(rng, fakers, person) if person.has_middle else None
            key = f"{fold(given.latin[0])}|{fold(surname.latin[0])}"
            surname_key = f"surname|{fold(surname.latin[0])}"
            if key in taken or (person.invented and surname_key in taken):
                continue
            if person.invented and not invented_ok(surname):
                continue
            if any(is_denied(name) for name in _full_names(given, middle, surname)):
                continue
            taken.update((key, surname_key) if person.invented else (key,))
            person.given, person.middle, person.surname = given, middle, surname
            break
        else:
            raise RuntimeError(f"no new {person.origin} name after {MAX_TRIES} tries")
    for twin in people:
        if twin.twin_of is None:
            continue
        original = by_number[twin.twin_of]
        twin.given, twin.surname = original.given, original.surname
        for attempt in range(MAX_TRIES):
            rng = _rng(seed, NAME, twin.number, attempt)
            twin.middle = _middle(rng, fakers, twin) if twin.has_middle else None
            shown = _full_names(twin.given, twin.middle, twin.surname)
            if not any(is_denied(name) for name in shown):
                break
        else:
            raise RuntimeError(f"no middle name for twin {twin.number} after {MAX_TRIES} tries")


def _details(seed: int, people: list[Person], by_number: dict[int, Person]) -> None:
    for person in sorted(people, key=lambda p: (p.twin_of is not None, p.number)):
        rng = _rng(seed, PERSON, person.number, 1)
        nationality = NATIONALITY["uk" if person.origin == "ru" and person.ukrainian
                                  else person.origin]  # fmt: skip
        first = pick(rng, nationality)
        second = pick(rng, [code for code in SECOND_NATIONALITY if code != first])
        person.nationalities = (
            (first, second) if chance(rng, RATES["second_nationality"]) else (first,)
        )
        original = by_number.get(person.twin_of or 0)
        if original is None:
            born = date(1940, 1, 1) + timedelta(days=between(rng, 0, 23740))
            code = postcode(rng)
        else:  # same birth year, the same month half of the time, another day
            months = [m for m in range(1, 13) if m != original.birth.month]
            month = original.birth.month if chance(rng, 0.5) else pick(rng, months)
            born = original.birth
            while born == original.birth:
                born = date(original.birth.year, month, between(rng, 1, 28))
            district = int(original.postcode[2:].split(" ")[0]) if chance(rng, 0.5) else None
            code = postcode(rng, district)
        person.birth, person.postcode, person.home = born, code, address(rng, code)


